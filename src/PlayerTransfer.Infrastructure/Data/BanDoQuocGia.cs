    /// <summary>Tra tên tiếng Việt và mã cờ. Không có trong bảng thì giữ nguyên tên gốc.</summary>
    public static (string TenViet, string MaCo) Tra(string tenTiengAnh)
    {
        if (string.IsNullOrWhiteSpace(tenTiengAnh)) return (null, null);

        var ten = tenTiengAnh.Trim();
        return Bang.TryGetValue(ten, out var ketQua) ? ketQua : (ten, null);
    }

    /// <summary>Đối chiếu ngược: tên tiếng Việt đã có sẵn trong CSDL mẫu.</summary>
    public static string TenVietTuTenAnh(string tenTiengAnh) => Tra(tenTiengAnh).TenViet;
